/**
 * WRITES THE SYNTHETIC AND HELD-OUT SETS: `npx tsx scenarios/synthetic/build.ts [--facts=<file>] [id ...]`. The ids select
 * from both (synthetic/specs.ts SPECS, design 6b; heldout/specs.ts HELDOUT, design 14); with none, it writes every one.
 * For each spec it writes scenarios/<id>/calendar.json (calendar.ts over the spec) and scenario.json, then loads the folder through the
 * loader and refuses (throws) unless every offered slot is free at the scenario's now and every named time a spec
 * relies on (`checks`) is free or not free as it says. --facts writes, per event, the facts condition A0 is shown, as the
 * vendored tools render them, so a reader can see what A sees without running a model.
 */
import fs from 'node:fs';
import path from 'node:path';
import { buildCalendar } from './calendar.js';
import { SPECS } from './specs.js';
import { HELDOUT } from '../heldout/specs.js';
import { TZ } from './common.js';
import { loadScenario, resolveEvent } from '../load.js';
import { buildWorld } from '../../conditions/world.js';
import { runSequence } from '../../conditions/sequence.js';
import type { ModelFn } from '../../models/types.js';

/** Every buildable spec: the synthetic set and the held-out set (ids do not overlap: s.., silent.. and h..). */
const ALL = { ...SPECS, ...HELDOUT };

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const local = (iso: string): string => new Intl.DateTimeFormat('sv-SE', { timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit' }).format(new Date(iso)).replace(' ', 'T');

/** A model that always waits: enough to make condition A render its facts. */
const waiter: ModelFn = (async () => ({ text: '{"thought":"","tool":"wait","args":{"why":"facts only"}}', inputTokens: 0, outputTokens: 0, cacheReadTokens: 0, cacheWriteTokens: 0, model: 'facts', latencyMs: 0, stopReason: 'end_turn', costUsd: 0 })) as unknown as ModelFn;

export async function buildOne(id: string): Promise<string> {
  const make = ALL[id];
  if (!make) throw new Error(`${id}: no such spec in synthetic/specs.ts or heldout/specs.ts`);
  const spec = make();
  const kind = id in HELDOUT ? 'HELD-OUT (design section 14)' : 'SYNTHETIC';
  const file = spec.file as { now: string; events: Array<{ now?: string }> };
  const dir = path.join(ROOT, id);
  fs.mkdirSync(dir, { recursive: true });
  const about = `Bob's calendar for scenario ${id}, ${kind}: generated by scenarios/synthetic/calendar.ts from his weekly pattern over ${spec.cal.from} to ${spec.cal.to} (Bob's zone, DST-aware), thinned per scenario, plus the scenario's own rows; sync rows as of now minus 15 minutes, ${spec.cal.horizonDays} days ahead. No real calendar is behind it.`;
  const cal = buildCalendar({ ...spec.cal, id, tz: TZ, now: file.now, about });
  fs.writeFileSync(path.join(dir, 'calendar.json'), `${JSON.stringify(cal, null, 1)}\n`);
  fs.writeFileSync(path.join(dir, 'scenario.json'), `${JSON.stringify(spec.file, null, 1)}\n`);
  const sc = loadScenario(id);
  const problems: string[] = [];
  const offered = [...(sc.initial.offered ?? []), ...sc.events.flatMap((e) => e.capture?.offered ?? [])];
  const w = buildWorld(sc);
  try {
    for (const o of offered) {
      const r = await w.lookups.checkCalendar({ times: [local(o.start)], durationMin: (Date.parse(o.end) - Date.parse(o.start)) / 60_000 });
      if (!r.slots[0]?.free) problems.push(`offer ${o.id} (${local(o.start)}) is not free: ${r.slots[0]?.inTheWay.join('; ')}`);
    }
  } finally { w.close(); }
  for (const c of spec.checks ?? []) {
    const ev = resolveEvent(sc, c.event ?? 0);
    const w2 = buildWorld(sc, { now: ev.now });
    try {
      const r = await w2.lookups.checkCalendar({ times: [c.at], durationMin: c.durationMin });
      if ((r.slots[0]?.free ?? false) !== c.free) problems.push(`${c.at} should be ${c.free ? 'free' : 'NOT free'} (${c.why}): ${r.slots[0]?.inTheWay.join('; ') || 'free'}`);
    } finally { w2.close(); }
  }
  if (problems.length) throw new Error(`${id}:\n  ${problems.join('\n  ')}`);
  // A0 is the condition that is shown precomputed facts (design 13, 2026-11-06: A became the raw-tools condition, which
  // gathers none, so running 'A' here printed every event with no facts).
  const runs = await runSequence('A0', sc, waiter, 'facts');
  return [`==== ${id}`, ...runs.map((r) => `-- event ${r.ev.index} (${r.ev.kind}, ${local(r.ev.now)}): ${r.ev.trigger}\n${(r.result.facts ?? []).map((f) => `${f.tool} ${JSON.stringify(f.args)}\n  -> ${f.result}`).join('\n')}`)].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const args = process.argv.slice(2);
  const factsOut = args.find((a) => a.startsWith('--facts='))?.slice(8);
  const ids = args.filter((a) => !a.startsWith('--'));
  const out: string[] = [];
  const failed: string[] = [];
  for (const id of ids.length ? ids : Object.keys(ALL)) {
    try { out.push(await buildOne(id)); console.log(`wrote ${id}`); } catch (e) { failed.push(String(e)); console.error(String(e)); }
  }
  if (factsOut) fs.writeFileSync(factsOut, `${out.join('\n\n')}\n`);
  if (failed.length) process.exit(1);
}
